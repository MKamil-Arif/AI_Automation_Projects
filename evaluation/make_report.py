"""
Turns evaluation/results.json into EVALUATION.md (tables ready for the project report).

    python evaluation/make_report.py
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results.json"
REPORT = HERE.parent / "EVALUATION.md"

TITLES = {
    "blood": "23 Blood Cell Counter", "flowers": "3 Flower Species", "leaves": "21 Leaf Species",
    "backbones": "Deep feature backbone (used by 2, 3, 8, 12, 14, 21)", "waste": "14 Waste Segregation",
    "fish": "2 Fish Species", "fer": "11 Emotion Recognition", "corel": "12 CBIR Search Engine",
    "leafdisease": "20 Leaf Disease", "plates": "5 Number Plate localisation", "potholes": "13 Potholes",
    "trees": "1 Tree Counting", "caption": "9 Image Captioning", "sr": "10 Super Resolution",
    "mask": "8 Mask detection", "helmet": "8 Helmet detection", "lfw": "4 Face Recognition",
    "watermark": "19 Watermark robustness", "restoration": "16 Old Photo Restoration", "cropweed": "24 Crop / Weed",
    "plateocr": "5 Number Plate reading (end to end)", "plateocr_gemini": "5 Number Plate reading with Gemini (cloud)",
    "fingerprint": "6 Fingerprint Matching",
    "background": "17 Background Remover", "fruit": "22 Fruit Ripeness", "copymove": "18 Copy-Move Forgery",
    "plates_yolo": "5 Plate detector training (YOLOv8n)", "potholes_yolo": "13 Pothole detector training (YOLOv8n)",
}


def table(rows: list[dict]) -> str:
    if not rows:
        return ""
    keys = list(rows[0])
    lines = ["| " + " | ".join(keys) + " |", "|" + "---|" * len(keys)]
    lines += ["| " + " | ".join(str(r.get(k, "")) for k in keys) + " |" for r in rows]
    return "\n".join(lines)


def section(key: str, r: dict) -> str:
    out = [f"## {TITLES.get(key, key)}", ""]
    scalars = {k: v for k, v in r.items() if not isinstance(v, (list, dict)) and k != "evaluated_in_s"}
    out.append(table([{"Metric": k, "Value": v} for k, v in scalars.items()]))
    for k, v in r.items():
        if isinstance(v, dict) and v and all(not isinstance(x, (dict, list)) for x in v.values()):
            out += ["", f"**{k}**", "", table([{"Name": a, "Value": b} for a, b in v.items()])]
        elif isinstance(v, dict) and v and all(isinstance(x, dict) for x in v.values()):
            out += ["", f"**{k}**", "", table([{"Name": a, **b} for a, b in v.items()])]
        elif isinstance(v, list) and v and isinstance(v[0], dict):
            out += ["", f"**{k}**", "", table(v[:40])]
    return "\n".join(out) + "\n"


def main() -> None:
    results = json.loads(RESULTS.read_text())
    parts = ["# Evaluation on real data", "",
             "Generated by `evaluation/make_report.py` from `evaluation/results.json`.",
             "Re-run everything with `python evaluation/fetch_datasets.py` then `python evaluation/evaluate_all.py`.", ""]
    topic_no = lambda k: int(TITLES[k].split()[0]) if TITLES.get(k, "x").split()[0].isdigit() else 99
    order = sorted((k for k in results if k in TITLES), key=topic_no) + [k for k in results if k not in TITLES]
    parts += [section(k, results[k]) for k in order]
    REPORT.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {REPORT}")


if __name__ == "__main__":
    main()
